"""Tenant persistence. `tenants` is the isolation root, so it has no tenant_id column;
callers must only ever pass the tenant id taken from the authenticated principal."""
import uuid
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.crud._errors import translate_integrity_errors
from app.models import Tenant


def get_by_id(db: Session, tenant_id: uuid.UUID) -> Tenant | None:
    return db.get(Tenant, tenant_id)


def get_by_slug(db: Session, slug: str) -> Tenant | None:
    return db.scalar(select(Tenant).where(Tenant.slug == slug.lower()))


def create_tenant(db: Session, *, name: str, slug: str, domain: str | None = None) -> Tenant:
    tenant = Tenant(name=name, slug=slug.lower(), domain=domain.lower() if domain else None)
    db.add(tenant)
    with translate_integrity_errors():
        db.flush()  # populates tenant.id (uuidv7 generated by PostgreSQL) via RETURNING
    return tenant


def update_tenant(db: Session, tenant: Tenant, changes: dict[str, Any]) -> Tenant:
    for field in ("name", "domain"):  # whitelist: never setattr arbitrary client keys
        if field in changes:
            setattr(tenant, field, changes[field])
    with translate_integrity_errors():
        db.flush()
    return tenant


def deactivate_tenant(db: Session, tenant: Tenant) -> Tenant:
    tenant.is_active = False
    db.flush()
    return tenant
